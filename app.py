def attachment_metadata(connection, attachment_ids: list[str], person: str, limit: int):
    ids = list(dict.fromkeys(attachment_ids))
    if len(ids) > limit:
        raise HTTPException(status_code=400, detail=f"Attach no more than {limit} files.")
    if not ids:
        return []
    placeholders = ", ".join("?" for _ in ids)
    rows = connection.execute(
        f"SELECT id, uploaded_by, filename, content_type, size FROM attachments WHERE id IN ({placeholders})",
        tuple(ids),
    ).fetchall()
    by_id = {row["id"]: row for row in rows}
    if len(by_id) != len(ids) or any(by_id[item]["uploaded_by"] != person for item in ids):
        raise HTTPException(status_code=400, detail="One of those files is unavailable. Please attach it again.")
    return [
        {
            "id": row["id"],
            "name": row["filename"],
            "content_type": row["content_type"],
            "size": row["size"],
        }
        for row in (by_id[item] for item in ids)
    ]


def valid_attachment_data(extension: str, data: bytes):
    if extension == ".jpg" or extension == ".jpeg":
        return data.startswith(b"\xff\xd8\xff")
    if extension == ".png":
        return data.startswith(b"\x89PNG\r\n\x1a\n")
    if extension == ".gif":
        return data.startswith((b"GIF87a", b"GIF89a"))
    if extension == ".webp":
        return len(data) >= 12 and data.startswith(b"RIFF") and data[8:12] == b"WEBP"
    if extension == ".pdf":
        return data.startswith(b"%PDF-")
    if extension == ".txt":
        try:
            data.decode("utf-8")
            return b"\x00" not in data
        except UnicodeDecodeError:
            return False
    if extension == ".docx":
        try:
            with zipfile.ZipFile(io.BytesIO(data)) as document:
                return "word/document.xml" in document.namelist()
        except (OSError, zipfile.BadZipFile):
            return False
    return False


def hash_phrase(phrase: str, salt: bytes | None = None):
    if salt is None:
        return "", password_hasher.hash(phrase.strip().casefold())
    salt = salt or secrets.token_bytes(16)
    phrase_hash = hashlib.pbkdf2_hmac(
        "sha256", phrase.strip().casefold().encode("utf-8"), salt, PASSWORD_ROUNDS
    )
    return salt.hex(), phrase_hash.hex()


def phrase_matches(phrase: str, salt: str, phrase_hash: str):
    if phrase_hash.startswith("$argon2"):
        try:
            password_hasher.verify(phrase_hash, phrase.strip().casefold())
            return True
        except (VerifyMismatchError, VerificationError):
            return False
    _, candidate_hash = hash_phrase(phrase, bytes.fromhex(salt))
    return hmac.compare_digest(candidate_hash, phrase_hash)


def needs_hash_upgrade(phrase_hash: str):
    return not phrase_hash.startswith("$argon2")


def session_person(token: str | None):
    if not token:
        return None
    token_hash = hashlib.sha256(token.encode("utf-8")).hexdigest()
    with database() as connection:
        row = connection.execute(
            "SELECT person, expires_at FROM sessions WHERE token_hash = ?", (token_hash,)
        ).fetchone()
        if row and row["expires_at"] <= int(time.time()):
            connection.execute("DELETE FROM sessions WHERE token_hash = ?", (token_hash,))
            return None
    return row["person"] if row else None


